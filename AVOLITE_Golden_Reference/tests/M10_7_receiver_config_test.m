    calculate_adaptive_receiver_config( ...
        0.0, ...
        1.0, ...
        "EXPLORE", ...
        cfg);

test3 = ...
    config3.rfFilterBandwidth_Hz >= baseRFBandwidth_Hz && ...
    config3.mode == "SEARCH";

