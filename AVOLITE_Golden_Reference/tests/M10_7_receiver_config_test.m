    isfinite(config1.gain_dB) && ...
    isfinite(config1.rfFilterBandwidth_Hz) && ...
    isfinite(config1.ifFilterBandwidth_Hz);

fprintf('\nM10.7.1 Baseline configuration:\n');
fprintf('    Gain = %.6f dB\n', config1.gain_dB);
fprintf('    RF BW = %.6f MHz\n', ...
    config1.rfFilterBandwidth_Hz / 1e6);
