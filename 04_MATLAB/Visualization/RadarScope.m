function RadarScope(Matched,Radar)

%=========================================================
% SARRS STUDIO
% Radar Scope
%
% Integrated Radar Display
%=========================================================

figure(...
    'Name','Radar Scope',...
    'NumberTitle','off',...
    'Color','k',...
    'Position',[100 100 1300 700]);

%% =====================================================
% Left Panel
%======================================================

subplot(1,2,1)

plot(...
    Matched.RangeAxis/1000,...
    abs(Matched.Output),...
    'g',...
    'LineWidth',1.5);

hold on

if Matched.NumberOfPeaks>0

    plot(...
        Matched.PeakRanges/1000,...
        Matched.Peaks,...
        'ro',...
        'MarkerFaceColor','r');

end

grid on

xlabel('Range (km)')
ylabel('Amplitude')

title('Matched Filter Output')

set(gca,...
    'Color','k',...
    'XColor','g',...
    'YColor','g');

%% =====================================================
% Right Panel
%======================================================

subplot(1,2,2)

axis off

text(0,0.95,...
    'SARRS STUDIO',...
    'Color','g',...
    'FontSize',18,...
    'FontWeight','bold');

text(0,0.88,...
    'SMART AI RADAR RESEARCH SIMULATOR',...
    'Color','w',...
    'FontSize',12);

text(0,0.78,...
    sprintf('Frequency : %.2f GHz',Radar.Frequency/1e9),...
    'Color','c',...
    'FontSize',11);

text(0,0.72,...
    sprintf('Power : %.0f W',Radar.Power),...
    'Color','c',...
    'FontSize',11);

text(0,0.66,...
    sprintf('Gain : %.1f dB',Radar.Gain),...
    'Color','c',...
    'FontSize',11);

text(0,0.60,...
    sprintf('Bandwidth : %.0f MHz',Radar.Bandwidth/1e6),...
    'Color','c',...
    'FontSize',11);

text(0,0.54,...
    sprintf('PRF : %.0f Hz',Radar.PRF),...
    'Color','c',...
    'FontSize',11);

text(0,0.48,...
    sprintf('Range Resolution : %.2f m',Radar.RangeResolution),...
    'Color','c',...
    'FontSize',11);

text(0,0.42,...
    sprintf('Detected Targets : %d',Matched.NumberOfPeaks),...
    'Color','y',...
    'FontSize',12,...
    'FontWeight','bold');

%% Target Table

y = 0.34;

if Matched.NumberOfPeaks>0

    for k = 1:Matched.NumberOfPeaks

        text(...
            0,...
            y,...
            sprintf('Target %d   %.0f m',...
            k,...
            Matched.PeakRanges(k)),...
            'Color','w',...
            'FontSize',10);

        y = y - 0.05;

    end

else

    text(...
        0,...
        y,...
        'No Targets',...
        'Color','r',...
        'FontSize',12);

end